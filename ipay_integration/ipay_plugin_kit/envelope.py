"""The signed and encrypted message format iPay uses with ERP plugins (iPay docs/collections-api.md, docs/erp-plugin-api.md).

    canonical = METHOD \\n TARGET \\n TIMESTAMP \\n NONCE \\n KID \\n hex(sha256(body))   signed with HMAC-SHA256
    body      = {"v":1,"kid","iv","ct","tag"}: AES-256-GCM, AAD = client|kid|timestamp|nonce|METHOD|TARGET

TARGET is the path plus any query string exactly as the other side sees it. An answer uses METHOD "RESPONSE", the same target
and the request's nonce, which is also carried inside the encrypted payload so an answer cannot be moved onto another request.

Tested byte for byte against iPay's own implementation (tests/vectors.json is generated by iPay's PHP Envelope).
"""

from __future__ import annotations

import base64
import hashlib
import hmac
import json
import os
import re
import time
from dataclasses import dataclass, field

from cryptography.exceptions import InvalidTag
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

RESPONSE = "RESPONSE"
H_CLIENT = "x-client-id"
H_KID = "x-ipay-key-id"
H_TIMESTAMP = "x-timestamp"
H_NONCE = "x-ipay-nonce"
H_SIGNATURE = "x-ipay-signature"
MAX_SKEW = 300

_NONCE = re.compile(r"^[A-Za-z0-9_-]{16,64}$")


class EnvelopeError(Exception):
    """A message that must be refused. `reason` is for the log; callers answer with a generic refusal."""

    def __init__(self, reason: str):
        super().__init__(reason)
        self.reason = reason


@dataclass(frozen=True)
class KeySet:
    """One direction's keys: encryption (AES-256-GCM) and signing (HMAC-SHA256), with the key id used for rotation."""

    kid: str
    enc_key: bytes = field(repr=False)
    sign_key: bytes = field(repr=False)

    @classmethod
    def from_base64(cls, kid: str, enc: str, sign: str) -> "KeySet":
        try:
            enc_key = base64.b64decode(enc or "", validate=True)
            sign_key = base64.b64decode(sign or "", validate=True)
        except Exception as exc:  # noqa: BLE001
            raise EnvelopeError("keys_not_configured") from exc
        if not kid or len(enc_key) != 32 or len(sign_key) != 32:
            raise EnvelopeError("keys_not_configured")
        return cls(kid, enc_key, sign_key)


def _b64url(raw: bytes) -> str:
    return base64.urlsafe_b64encode(raw).rstrip(b"=").decode()


def canonical(method: str, target: str, timestamp: int, nonce: str, kid: str, body: str) -> str:
    return "\n".join([method.upper(), target, str(timestamp), nonce, kid, hashlib.sha256(body.encode()).hexdigest()])


def _aad(client_id: str, kid: str, timestamp: int, nonce: str, method: str, target: str) -> bytes:
    return "|".join([client_id, kid, str(timestamp), nonce, method, target]).encode()


def _signature(keys: KeySet, method: str, target: str, timestamp: int, nonce: str, body: str) -> str:
    mac = hmac.new(keys.sign_key, canonical(method, target, timestamp, nonce, keys.kid, body).encode(), hashlib.sha256).digest()
    return base64.b64encode(mac).decode()


def seal(keys: KeySet, client_id: str, method: str, target: str, payload: dict, nonce: str | None = None, timestamp: int | None = None) -> dict:
    """Encrypts and signs a message. Returns {"headers", "body", "nonce"}."""
    method = method.upper()
    timestamp = int(time.time()) if timestamp is None else timestamp
    nonce = nonce or _b64url(os.urandom(16))
    iv = os.urandom(12)
    plain = json.dumps(payload, separators=(",", ":"), ensure_ascii=True).encode()
    sealed = AESGCM(keys.enc_key).encrypt(iv, plain, _aad(client_id, keys.kid, timestamp, nonce, method, target))
    ct, tag = sealed[:-16], sealed[-16:]
    body = json.dumps({"v": 1, "kid": keys.kid, "iv": base64.b64encode(iv).decode(), "ct": base64.b64encode(ct).decode(), "tag": base64.b64encode(tag).decode()}, separators=(",", ":"))
    return {
        "headers": {
            H_CLIENT: client_id,
            H_KID: keys.kid,
            H_TIMESTAMP: str(timestamp),
            H_NONCE: nonce,
            H_SIGNATURE: _signature(keys, method, target, timestamp, nonce, body),
        },
        "body": body,
        "nonce": nonce,
    }


def sign_only(keys: KeySet, client_id: str, method: str, target: str, nonce: str | None = None, timestamp: int | None = None) -> dict:
    """Headers for a request with no body (GET): the same signature over an empty body. Returns {"headers", "nonce"}."""
    timestamp = int(time.time()) if timestamp is None else timestamp
    nonce = nonce or _b64url(os.urandom(16))
    return {
        "headers": {
            H_CLIENT: client_id,
            H_KID: keys.kid,
            H_TIMESTAMP: str(timestamp),
            H_NONCE: nonce,
            H_SIGNATURE: _signature(keys, method.upper(), target, timestamp, nonce, ""),
        },
        "nonce": nonce,
    }


def _lower(headers) -> dict:
    return {str(k).lower(): (v[0] if isinstance(v, (list, tuple)) else str(v)) for k, v in dict(headers).items()}


def _check_headers(keys: dict, client_id: str, h: dict, now: float, max_skew: int):
    if not hmac.compare_digest(client_id, h.get(H_CLIENT, "")):
        raise EnvelopeError("unknown_client")
    kid = h.get(H_KID, "")
    key_set = keys.get(kid)
    if key_set is None:
        raise EnvelopeError("unknown_key")
    timestamp = h.get(H_TIMESTAMP, "")
    if not timestamp.isdigit() or abs(now - int(timestamp)) > max_skew:
        raise EnvelopeError("stale_timestamp")
    nonce = h.get(H_NONCE, "")
    if not _NONCE.match(nonce):
        raise EnvelopeError("bad_nonce")
    return kid, key_set, int(timestamp), nonce


def open_(keys: dict, client_id: str, method: str, target: str, headers, body: str, claim_nonce=None, expect_nonce: str | None = None, max_skew: int = MAX_SKEW, now: float | None = None) -> dict:
    """Verifies and decrypts a message. Checks, in order: client and key id, clock window, signature, unused nonce, decryption, JSON.

    `keys` maps key id to KeySet (the current one, and the previous during a rotation). `claim_nonce(kid, nonce)` must return False
    if the nonce was seen before. Raises EnvelopeError; the caller answers with a generic refusal.
    """
    method = method.upper()
    now = time.time() if now is None else now
    h = _lower(headers)
    kid, key_set, timestamp, nonce = _check_headers(keys, client_id, h, now, max_skew)
    if expect_nonce is not None and not hmac.compare_digest(expect_nonce, nonce):
        raise EnvelopeError("nonce_mismatch")
    if not hmac.compare_digest(_signature(key_set, method, target, timestamp, nonce, body), h.get(H_SIGNATURE, "")):
        raise EnvelopeError("bad_signature")
    # Claimed only once the signature is good, so unsigned traffic cannot use up nonces.
    if claim_nonce is not None and not claim_nonce(kid, nonce):
        raise EnvelopeError("replayed_nonce")
    try:
        env = json.loads(body)
    except ValueError as exc:
        raise EnvelopeError("bad_envelope") from exc
    if not isinstance(env, dict) or env.get("v") != 1 or env.get("kid") != kid:
        raise EnvelopeError("bad_envelope")
    try:
        iv = base64.b64decode(str(env.get("iv", "")), validate=True)
        ct = base64.b64decode(str(env.get("ct", "")), validate=True)
        tag = base64.b64decode(str(env.get("tag", "")), validate=True)
    except Exception as exc:  # noqa: BLE001
        raise EnvelopeError("bad_envelope") from exc
    if len(iv) != 12 or len(tag) != 16:
        raise EnvelopeError("bad_envelope")
    try:
        plain = AESGCM(key_set.enc_key).decrypt(iv, ct + tag, _aad(client_id, kid, timestamp, nonce, method, target))
    except InvalidTag as exc:
        raise EnvelopeError("decrypt_failed") from exc
    try:
        payload = json.loads(plain)
    except ValueError as exc:
        raise EnvelopeError("bad_payload") from exc
    if not isinstance(payload, dict):
        raise EnvelopeError("bad_payload")
    if expect_nonce is not None and not hmac.compare_digest(expect_nonce, str(payload.get("nonce", ""))):
        raise EnvelopeError("nonce_mismatch")
    return payload


def verify_only(keys: dict, client_id: str, method: str, target: str, headers, body: str, claim_nonce=None, max_skew: int = MAX_SKEW, now: float | None = None) -> str:
    """The receiving side of sign_only(): the same header checks, and the body must be empty. Returns the nonce."""
    if body != "":
        raise EnvelopeError("unexpected_body")
    now = time.time() if now is None else now
    h = _lower(headers)
    kid, key_set, timestamp, nonce = _check_headers(keys, client_id, h, now, max_skew)
    if not hmac.compare_digest(_signature(key_set, method.upper(), target, timestamp, nonce, ""), h.get(H_SIGNATURE, "")):
        raise EnvelopeError("bad_signature")
    if claim_nonce is not None and not claim_nonce(kid, nonce):
        raise EnvelopeError("replayed_nonce")
    return nonce
